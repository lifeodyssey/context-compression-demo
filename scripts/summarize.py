lines += ['## Reproducibility boundary', '',
          'The seeded data generator is deterministic. Pytest timing, platform headers, absolute working directory, RTK recall hashes, CodeGraph progress messages, and temporary paths can vary on another run; rerun the ledger instead of assuming byte-for-byte stability. Raw pytest and RTK each execute the same suite separately. The regression is intentionally not fixed. No model API or real GitHub issue/log service is called.', '']

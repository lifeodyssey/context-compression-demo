for name in ['cart_total', 'apply_coupon', 'explore']:
    item = cg['commands'][name]
    lines.append(f"| [{name}](codegraph/{name}.txt) | {item['stdout_bytes']:,} | {item['stdout_lines']} | {item.get('symbols_returned', '—')} | {item.get('files_returned', '—')} |")
